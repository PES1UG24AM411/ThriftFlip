#!/usr/bin/env python3
"""Builds docs/ER_AND_DATA_DICTIONARY.md from the SQL migration files.

The Mermaid ER diagram and the data dictionary are generated from the same
CREATE TABLE / ALTER TABLE statements that create the database, so the
documentation cannot drift away from the real schema.

Run:  python3 scripts/gen_docs.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIGRATIONS = sorted((ROOT / "db" / "migrations").glob("*.sql"))
OUT = ROOT / "docs" / "ER_AND_DATA_DICTIONARY.md"

TABLE_START = re.compile(r"^CREATE TABLE (\w+) \($")
ALTER_CHECK = re.compile(r"^ALTER TABLE (\w+) ADD CONSTRAINT (\w+) CHECK \((.*)\);$")
FK = re.compile(r"REFERENCES (\w+)\((\w+)\)")
TYPE = re.compile(r"^(\w+(?:\(\d+(?:,\s*\d+)?\))?)\s*(.*)$")

tables = {}   # name -> {"columns": [...], "table_constraints": [...], "checks": [...]}
order = []

for path in MIGRATIONS:
    current = None
    for raw in path.read_text(encoding="utf8").splitlines():
        line = raw.strip()
        m = TABLE_START.match(line)
        if m:
            current = m.group(1)
            tables[current] = {"columns": [], "table_constraints": [], "checks": []}
            order.append(current)
            continue
        if current and line == ");":
            current = None
            continue
        if current:
            if not line or line.startswith("--"):
                continue
            if line.startswith("PRIMARY KEY") or line.startswith("UNIQUE"):
                tables[current]["table_constraints"].append(line.rstrip(","))
                continue
            body, _, desc = line.partition("--")
            body = body.strip().rstrip(",")
            name, _, rest = body.partition(" ")
            tm = TYPE.match(rest.strip())
            tables[current]["columns"].append(
                {"name": name, "type": tm.group(1), "constraints": tm.group(2), "desc": desc.strip()}
            )
            continue
        a = ALTER_CHECK.match(line)
        if a:
            tables[a.group(1)]["checks"].append((a.group(2), a.group(3)))

# ---- Mermaid ER diagram ----
er = ["erDiagram"]
relations = []
for t in order:
    pk_cols = set()
    for tc in tables[t]["table_constraints"]:
        if tc.startswith("PRIMARY KEY"):
            pk_cols |= {c.strip() for c in tc[tc.index("(") + 1:tc.index(")")].split(",")}
    er.append(f"    {t} {{")
    for c in tables[t]["columns"]:
        tag = []
        is_pk = "PRIMARY KEY" in c["constraints"] or c["name"] in pk_cols
        fk = FK.search(c["constraints"])
        if is_pk:
            tag.append("PK")
        if fk:
            tag.append("FK")
        elif "UNIQUE" in c["constraints"] and not is_pk:
            tag.append("UK")
        mtype = re.sub(r"\(.*\)", "", c["type"])
        er.append(f"        {mtype} {c['name']}" + (f" {','.join(tag)}" if tag else ""))
        if fk:
            parent = fk.group(1)
            mandatory = "NOT NULL" in c["constraints"] or is_pk
            one_to_one = ("UNIQUE" in c["constraints"] or "PRIMARY KEY" in c["constraints"])
            left = "||" if mandatory else "|o"
            right = "o|" if one_to_one else "o{"
            relations.append(f'    {parent} {left}--{right} {t} : "{c["name"]}"')
    er.append("    }")
er.extend(relations)

# ---- Markdown ----
md = []
md.append("# THRIFTFLIP: ER diagram and data dictionary\n")
md.append("_Generated by `scripts/gen_docs.py` from `db/migrations/*.sql`. Do not edit by hand; edit the SQL and re-run the script._\n")
md.append("Relationship notation: `||` exactly one, `|o` zero or one, `o{` zero or many, `o|` zero or one (one-to-one).\n")
md.append("## ER diagram\n")
md.append("```mermaid\n" + "\n".join(er) + "\n```\n")
md.append("## Relational schema\n")
for t in order:
    cols = []
    for c in tables[t]["columns"]:
        name = c["name"]
        if "PRIMARY KEY" in c["constraints"]:
            name = f"__{name}__"
        fk = FK.search(c["constraints"])
        if fk:
            name += f" (FK -> {fk.group(1)})"
        cols.append(name)
    md.append(f"- **{t}**({', '.join(cols)})")
md.append("")
md.append("## Data dictionary\n")
for t in order:
    md.append(f"### {t}\n")
    md.append("| Column | Type | Constraints | Description |")
    md.append("|---|---|---|---|")
    for c in tables[t]["columns"]:
        cons = c["constraints"].replace("|", "\\|") or "-"
        md.append(f"| {c['name']} | {c['type']} | {cons} | {c['desc']} |")
    if tables[t]["table_constraints"]:
        md.append("")
        md.append("Table constraints: " + "; ".join(f"`{x}`" for x in tables[t]["table_constraints"]))
    if tables[t]["checks"]:
        md.append("")
        md.append("CHECK constraints:")
        for name, expr in tables[t]["checks"]:
            md.append(f"- `{name}`: `{expr}`")
    md.append("")

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(md), encoding="utf8")
print(f"Wrote {OUT} ({len(order)} tables, {len(relations)} relationships)")
